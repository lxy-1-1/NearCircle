CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(32) NOT NULL UNIQUE,
 display_name VARCHAR(40) NOT NULL,
 bio VARCHAR(200) NOT NULL DEFAULT '',
 password_hash VARCHAR(256) NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash VARCHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS friend_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 from_id BIGINT NOT NULL REFERENCES users(id),
 to_id BIGINT NOT NULL REFERENCES users(id),
 status VARCHAR(16) NOT NULL,
 created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS friendships (
 user_id BIGINT NOT NULL REFERENCES users(id),
 friend_id BIGINT NOT NULL REFERENCES users(id),
 PRIMARY KEY(user_id,friend_id)
);
CREATE TABLE IF NOT EXISTS messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 client_id VARCHAR(80) NOT NULL,
 sender_id BIGINT NOT NULL REFERENCES users(id),
 recipient_id BIGINT NOT NULL REFERENCES users(id),
 body VARCHAR(2000) NOT NULL,
 created_at BIGINT NOT NULL,
 read_at BIGINT,
 UNIQUE(sender_id,client_id)
);
CREATE INDEX IF NOT EXISTS ix_messages_pair ON messages(sender_id,recipient_id,id);
CREATE TABLE IF NOT EXISTS media (
 id VARCHAR(36) PRIMARY KEY,
 owner_id BIGINT NOT NULL REFERENCES users(id),
 content BLOB NOT NULL
);
CREATE TABLE IF NOT EXISTS posts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 author_id BIGINT NOT NULL REFERENCES users(id),
 body VARCHAR(2000) NOT NULL,
 media_id VARCHAR(36) REFERENCES media(id),
 created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS post_likes (
 post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id),
 PRIMARY KEY(post_id,user_id)
);
CREATE TABLE IF NOT EXISTS comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 author_id BIGINT NOT NULL REFERENCES users(id),
 body VARCHAR(500) NOT NULL,
 created_at BIGINT NOT NULL
);
